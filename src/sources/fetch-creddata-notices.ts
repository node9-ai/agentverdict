// Writes sources/creddata/REPOSITORY-NOTICES.md: the copyright notice of each
// of the 60 repositories CredData lines were taken from, read from the
// repository's own licence file at the exact commit CredData labelled, plus
// the repository's NOTICE file where an Apache-2.0 project has one. MIT, BSD
// and ISC ask that the copyright notice travel with the content; Apache-2.0
// asks the same of a NOTICE file. This file is how the corpus meets that.
//
//   npm run sources:creddata-notices
//
// Uses the GitHub API through the gh CLI (about 120 requests, authenticated,
// read-only). The repository list and commits come from
// sources/creddata/snapshot.json, so the output only changes when the sample
// does.

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from '../corpus.ts';

interface Repo {
  repo: string;
  url: string;
  commit: string;
  license: string;
}

const DIR = path.join(ROOT, 'sources', 'creddata');
const OUT = path.join(DIR, 'REPOSITORY-NOTICES.md');

function gh(endpoint: string): Record<string, unknown> | null {
  try {
    return JSON.parse(execFileSync('gh', ['api', endpoint], { encoding: 'utf-8', stdio: ['ignore', 'pipe', 'ignore'] }));
  } catch {
    return null;
  }
}

const decode = (b64: unknown) => Buffer.from(String(b64), 'base64').toString('utf-8');

/** The copyright lines of a licence text, as written. */
export function copyrightLines(text: string): string[] {
  return text
    .split('\n')
    .map((l) => l.trim())
    // "(c)" counts only before a year: Apache-2.0 section 4 has a clause "(c) You must retain".
    .filter((l) => /^(copyright\b|©|\(c\)\s*\d)/i.test(l) && !/copyright (notice|owner|holder|license|\[yyyy\]|\{yyyy\}|yyyy)/i.test(l));
}

/** The notice lines of one repository at its commit, as REPOSITORY-NOTICES.md writes them. */
export function noticeOf(r: Repo): string[] {
  const slug = r.url.replace('https://github.com/', '');
  const lic = gh(`repos/${slug}/license?ref=${r.commit}`);
  const text = lic ? decode(lic.content) : '';
  const lines = copyrightLines(text);
  const L = [`## ${slug}`, '', `- Commit: \`${r.commit}\``, `- Licence: ${r.license}` + (lic ? ` (\`${lic.path}\`)` : ' (licence file not found at this commit)')];
  if (lines.length > 0) L.push('- Notice:', '', ...lines.map((l) => `  > ${l}`), '');
  else L.push(`- Notice: the licence file names no copyright holder; the copyright belongs to the contributors of ${slug}.`, '');
  if (r.license === 'Apache-2.0') {
    const notice = gh(`repos/${slug}/contents/NOTICE?ref=${r.commit}`);
    if (notice?.content) L.push('- NOTICE file:', '', ...decode(notice.content).trim().split('\n').map((l) => `  > ${l}`), '');
  }
  return L;
}

function main(): void {
  const full = JSON.parse(fs.readFileSync(path.join(DIR, 'snapshot.json'), 'utf-8')) as { revision: string; repos: Repo[]; held_extra?: { repositories?: string[] } };
  // The repositories of the held-out draw (7.0.0) keep their notices in the
  // holdout (held_extra.notices): this file is copied whole to the public repository.
  const heldOnly = new Set(full.held_extra?.repositories ?? []);
  const snap = { ...full, repos: full.repos.filter((r) => !heldOnly.has(r.repo)) };
  const L: string[] = [
    '# CredData source repositories: copyright notices',
    '',
    'Each line of `snapshot.json` comes from one of the repositories below, at the',
    'commit shown, under the licence shown. The notices are quoted from each',
    "repository's licence file (and NOTICE file, where an Apache-2.0 project has",
    'one) at that commit. Generated by `npm run sources:creddata-notices`.',
    '',
  ];
  const missing: string[] = [];
  for (const r of [...snap.repos].sort((a, b) => a.url.localeCompare(b.url))) {
    const slug = r.url.replace('https://github.com/', '');
    const lic = gh(`repos/${slug}/license?ref=${r.commit}`);
    const text = lic ? decode(lic.content) : '';
    const lines = copyrightLines(text);
    L.push(`## ${slug}`, '', `- Commit: \`${r.commit}\``, `- Licence: ${r.license}` + (lic ? ` (\`${lic.path}\`)` : ' (licence file not found at this commit)'));
    if (lines.length > 0) {
      L.push('- Notice:', '', ...lines.map((l) => `  > ${l}`), '');
    } else {
      L.push(`- Notice: the licence file names no copyright holder; the copyright belongs to the contributors of ${slug}.`, '');
      if (r.license !== 'Apache-2.0') missing.push(slug);
    }
    if (r.license === 'Apache-2.0') {
      const notice = gh(`repos/${slug}/contents/NOTICE?ref=${r.commit}`);
      if (notice?.content) L.push('- NOTICE file:', '', ...decode(notice.content).trim().split('\n').map((l) => `  > ${l}`), '');
    }
  }
  fs.writeFileSync(OUT, L.join('\n').replace(/\n+$/, '') + '\n');
  console.log(`${snap.repos.length} repositories written to ${path.relative(ROOT, OUT)}`);
  if (missing.length > 0) console.log(`no copyright line in the licence file of: ${missing.join(', ')}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) main();
